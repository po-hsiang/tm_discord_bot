def weekday_name(now):
    return WEEK_LIST[now.weekday()]


def morning_greeting(now, time_str, holiday_line=""):
    """早安招呼語；holiday_line 為節日彩蛋指示（平日為空字串）。"""
    return f"""早安，現在時間是{weekday_name(now)} {time_str}，
想請妳給各位好虎粉一段充滿活力的招呼語！不用特別提到虎喵，妳只需祝福好虎粉就好✨
{holiday_line}接著請用 tw_weather 工具取得臺灣今日總體天氣，用一兩句話播報重點並附上貼心提醒
（如帶傘、防曬、保暖），自然融入訊息、不要像制式氣象報告；若天氣暫時取不到就略過、照常打招呼。
每天的招呼語跟 emoji 記得都要有變化，全篇約 100 個臺灣繁體中文字元左右。
emoji 與前後的文字之間一律留一個半形空格，不要讓文字黏在 emoji 上。"""


